def calculate_classification_metrics(
    true_labels: List[str],
    predicted_labels: List[str],
    confidences: Optional[List[float]] = None
) -> Dict[str, Any]:
    """
    计算分类指标：准确率、精确率、召回率、F1值（宏平均和加权平均）
    
    参数：
        true_labels: 真实标签列表
        predicted_labels: 预测标签列表
        confidences: 预测置信度列表（可选）
    """
    from sklearn.metrics import (
        accuracy_score, precision_score, recall_score,
        f1_score, classification_report, confusion_matrix
    )
    
    labels = sorted(list(set(true_labels + predicted_labels)))
    
    # 整体准确率
    accuracy = accuracy_score(true_labels, predicted_labels)
    
    # 每个标签的精确率、召回率、F1
    precision_per_label = precision_score(true_labels, predicted_labels, labels=labels, average=None, zero_division=0)
    recall_per_label = recall_score(true_labels, predicted_labels, labels=labels, average=None, zero_division=0)
    f1_per_label = f1_score(true_labels, predicted_labels, labels=labels, average=None, zero_division=0)
    
    # 宏平均（每个标签权重相同）
    macro_precision = precision_score(true_labels, predicted_labels, labels=labels, average='macro', zero_division=0)
    macro_recall = recall_score(true_labels, predicted_labels, labels=labels, average='macro', zero_division=0)
    macro_f1 = f1_score(true_labels, predicted_labels, labels=labels, average='macro', zero_division=0)
    
    # 加权平均（按样本数加权）
    weighted_precision = precision_score(true_labels, predicted_labels, labels=labels, average='weighted', zero_division=0)
    weighted_recall = recall_score(true_labels, predicted_labels, labels=labels, average='weighted', zero_division=0)
    weighted_f1 = f1_score(true_labels, predicted_labels, labels=labels, average='weighted', zero_division=0)
    
    # 置信度统计
    confidence_stats = {}
    if confidences:
        confidence_stats = {
            'mean_confidence': np.mean(confidences),
            'median_confidence': np.median(confidences),
            'low_confidence_ratio': sum(1 for c in confidences if c < 0.6) / len(confidences),
            'high_confidence_ratio': sum(1 for c in confidences if c >= 0.8) / len(confidences)
        }
    
    # 分类报告
    report = classification_report(true_labels, predicted_labels, labels=labels, output_dict=True, zero_division=0)
    
    return {
        'accuracy': round(accuracy, 4),
        'macro_precision': round(macro_precision, 4),
        'macro_recall': round(macro_recall, 4),
        'macro_f1': round(macro_f1, 4),
        'weighted_precision': round(weighted_precision, 4),
        'weighted_recall': round(weighted_recall, 4),
        'weighted_f1': round(weighted_f1, 4),
        'per_label': {
            label: {
                'precision': round(precision_per_label[i], 4) if not np.isnan(precision_per_label[i]) else 0.0,
                'recall': round(recall_per_label[i], 4) if not np.isnan(recall_per_label[i]) else 0.0,
                'f1': round(f1_per_label[i], 4) if not np.isnan(f1_per_label[i]) else 0.0,
            }
            for i, label in enumerate(labels)
        },
        'confidence_stats': confidence_stats,
        'report': report
    }


def calculate_attribution_metrics(
    true_gmv: List[float],
    predicted_gmv: List[float]
) -> Dict[str, float]:
    """
    计算归因模型误差指标：MAE、RMSE、MAPE
    
    参数：
        true_gmv: 真实GMV列表
        predicted_gmv: 预测GMV列表
    """
    true_arr = np.array(true_gmv)
    pred_arr = np.array(predicted_gmv)
    
    # MAE（平均绝对误差）
    mae = np.mean(np.abs(true_arr - pred_arr))
    
    # RMSE（均方根误差）
    rmse = np.sqrt(np.mean((true_arr - pred_arr) ** 2))
    
    # MAPE（平均绝对百分比误差）
    mape = np.mean(np.abs((true_arr - pred_arr) / (true_arr + 1e-8))) * 100
    
    return {
        'mae': round(mae, 2),
        'rmse': round(rmse, 2),
        'mape': round(mape, 2)
    }


def calculate_business_metrics(
    baseline_conversion_rate: float,
    optimized_conversion_rate: float,
    baseline_gmv: float,
    optimized_gmv: float,
    high_conversion_precision: float,
    high_conversion_recall: float
) -> Dict[str, Any]:
    """
    计算业务指标
    
    参数：
        baseline_conversion_rate: 优化前转化率
        optimized_conversion_rate: 优化后转化率
        baseline_gmv: 优化前GMV
        optimized_gmv: 优化后GMV
        high_conversion_precision: 高转化话术识别的精确率
        high_conversion_recall: 高转化话术识别的召回率
    """
    # 转化率提升率
    conversion_lift = ((optimized_conversion_rate - baseline_conversion_rate) / baseline_conversion_rate * 100) if baseline_conversion_rate > 0 else 0
    
    # ROI提升幅度
    roi_lift = ((optimized_gmv - baseline_gmv) / baseline_gmv * 100) if baseline_gmv > 0 else 0
    
    return {
        'conversion_rate_lift': round(conversion_lift, 2),
        'optimized_conversion_rate': round(optimized_conversion_rate, 4),
        'high_conversion_precision': round(high_conversion_precision, 4),
        'high_conversion_recall': round(high_conversion_recall, 4),
        'roi_lift': round(roi_lift, 2),
        'optimized_gmv': round(optimized_gmv, 2),
        'gmv_increase': round(optimized_gmv - baseline_gmv, 2)
    }


def run_evaluation(
    classifier=None,
    dataset: Optional[List[AnnotatedScript]] = None
) -> Dict[str, Any]:
    """
    运行完整评测
    
    参数：
        classifier: 分类器实例（如果None则使用规则分类器）
        dataset: 评测数据集（如果None则使用内置数据集）
        
    返回：
        包含所有评测指标的字典
    """
    from core.script_classifier import SimpleRuleClassifier
    
    if dataset is None:
        dataset = build_evaluation_dataset()
    
    if classifier is None:
        classifier = SimpleRuleClassifier()
    
    # 运行分类
    texts = [s.text for s in dataset]
    true_labels = [s.true_label for s in dataset]
    
    results = classifier.classify_batch(texts)
    predicted_labels = [r.predicted_label for r in results]
    confidences = [r.confidence for r in results]
    
    # 计算分类指标
    classification_metrics = calculate_classification_metrics(
        true_labels, predicted_labels, confidences
    )
    
    # 计算业务指标（使用模拟数据）
    business_metrics = calculate_business_metrics(
        baseline_conversion_rate=0.035,
        optimized_conversion_rate=0.048,
        baseline_gmv=15000,
        optimized_gmv=19500,
        high_conversion_precision=0.85,
        high_conversion_recall=0.78
    )
    
    # 计算归因误差（使用模拟数据）
    attribution_metrics = calculate_attribution_metrics(
        true_gmv=[150, 200, 80, 120, 50, 300, 180, 90],
        predicted_gmv=[140, 210, 75, 130, 55, 280, 170, 95]
    )
    
    # 获取Bad Case
    bad_cases = build_bad_cases()
    
    # 数据集统计
    dataset_stats = {
        'total_samples': len(dataset),
        'categories': {
            cat: len([s for s in dataset if s.category == cat])
            for cat in ['美妆', '服饰', '家居']
        },
        'labels': {
            label: len([s for s in dataset if s.true_label == label])
            for label in sorted(set(true_labels))
        },
        'time_slots': {
            slot: len([s for s in dataset if s.time_slot == slot])
            for slot in ['上午', '下午', '晚场']
        },
        'host_types': {
            ht: len([s for s in dataset if s.host_type == ht])
            for ht in ['头部', '腰部', '新人']
        }
    }
    
    return {
        'classification_metrics': classification_metrics,
        'attribution_metrics': attribution_metrics,
        'business_metrics': business_metrics,
        'bad_cases': bad_cases,
        'dataset_stats': dataset_stats
    }


