    def classify_single(self, text: str, segment_id: int = 0) -> ClassificationResult:
        """
        使用规则对单条话术分类
        
        算法：关键词计数投票，得票最多的标签获胜
        """
        text_lower = text.lower()
        scores = {}
        
        for label, keywords in self.rules.items():
            score = sum(1 for keyword in keywords if keyword in text_lower)
            scores[label] = score
        
        max_score = max(scores.values())
        
        if max_score == 0:
            predicted_label = "其他"
            confidence = 0.3
        else:
            top_labels = [label for label, score in scores.items() if score == max_score]
            predicted_label = top_labels[0]
            confidence = min(0.9, 0.5 + max_score * 0.1)
        
        # 归一化分数
        total_score = sum(scores.values())
        if total_score > 0:
            all_scores = {label: score / total_score for label, score in scores.items()}
        else:
            all_scores = {label: 0.0 for label in self.rules.keys()}
        all_scores["其他"] = 0.0
        
        return ClassificationResult(
            segment_id=segment_id,
            text=text,
            predicted_label=predicted_label,
            confidence=confidence,
            all_scores=all_scores
        )
    
    def classify_batch(
        self,
        texts: List[str],
        segment_ids: Optional[List[int]] = None,
        progress_callback=None
    ) -> List[ClassificationResult]:
        """批量规则分类"""
        if segment_ids is None:
            segment_ids = list(range(len(texts)))
        
        results = []
        for i, (text, seg_id) in enumerate(zip(texts, segment_ids)):
            result = self.classify_single(text, seg_id)
            results.append(result)
            
            if progress_callback and (i + 1) % 50 == 0:
                progress = (i + 1) / len(texts)
                progress_callback(progress, f"已分类 {i+1}/{len(texts)} 条话术")
        
        if progress_callback:
            progress_callback(1.0, f"分类完成！共{len(results)}条话术")
        
        return results


