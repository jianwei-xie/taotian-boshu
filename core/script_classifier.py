# │ 售后承诺 │ 主播在承诺售后保障，消除购买顾虑。                                │
# │          │ 标注标准：包含退换货政策、质量保证、客服承诺等保障性信息。         │
# │          │ 关键词：退换、退货、退款、售后、无理由、不满意、包赔、放心。       │
# │          │ 典型话术："不满意7天无理由退换货"                                   │
# ├──────────┼──────────────────────────────────────────────────────────────────┤
# │ 其他     │ 以上8个标签都无法匹配的话术。                                      │
# │          │ 标注标准：模型置信度低于阈值，或话术内容不属于任何类别。           │
# │          │ 典型话术："好的好的""可以可以"等无意义的口语                        │
# └──────────┴──────────────────────────────────────────────────────────────────┘
#
# 【标签间的边界处理规则】
# - "今天只要99，库存只剩最后20单" → 价格福利优先（价格信息更具体）
# - "这款面膜补水效果特别好，拍下立减50" → 产品介绍优先（产品信息在前）
# - "用过的姐妹扣个1，我们好评率99%" → 互动引导优先（当前动作指令优先）
# - 当两个标签得分差距<0.05时，取置信度更高的那个
