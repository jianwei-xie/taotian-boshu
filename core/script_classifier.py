#
# 【方向1：领域微调（Domain Fine-tuning）】
# 预期提升：F1 从 0.85 → 0.92+
#
# 方案：在真实直播话术数据上对 uer/roberta-base-finetuned-dianping-chinese
#       做进一步微调
#
# 数据需求：
# - 至少2000条人工标注的直播话术（每个标签约250条）
# - 标注规范：每段话术只标注一个主标签
# - 数据来源：从淘天播术-电商直播话术军师的历史分析结果中筛选高置信度样本
#
# 微调策略：
# - 使用LoRA（Low-Rank Adaptation）降低显存需求
# - 学习率：2e-5，训练3个epoch
# - 分类头：8分类线性层（替换原模型的MLM头）
# - 验证集划分：80%训练 / 10%验证 / 10%测试
#
# 优势：
# - 对直播特有词汇（"到手价""扣1""拍一发三"）理解更准确
# - 对标签边界模糊的话术（如"今天只要99赶紧拍"）判断更精准
# - 推理速度不变（模型大小不变）
#
# 挑战：
# - 需要大量高质量标注数据
# - 不同品类（美妆/服饰/食品）可能需要分别微调
# - 需要定期更新模型（直播话术风格会随时间变化）
#
# 【方向2：Few-Shot学习（Prompt Engineering）】
# 预期提升：F1 从 0.85 → 0.88
#
# 方案：在零样本分类的prompt中添加每个标签的示例话术
#
# 实现方式：
# - 将LABEL_DEFINITIONS中的examples直接嵌入prompt
# - 使用SetFit等Few-Shot框架，用极少样本（每标签10条）快速适配
# - 或使用In-Context Learning，在prompt中拼接示例
#
# 优势：
# - 不需要大量标注数据（每标签10-50条即可）
# - 可以针对不同品类快速切换示例
# - 实现简单，不需要训练
#
# 挑战：
# - prompt长度增加，推理速度下降约20%
# - 示例选择对结果影响大，需要精心挑选
#
# 【方向3：多标签分类（Multi-Label Classification）】
# 预期提升：覆盖更全面，但F1可能略降
#
# 方案：允许一段话术同时属于多个标签
#
# 场景：
# - "今天只要99赶紧拍" → [价格福利, 逼单催促]
# - "这款面膜补水效果特别好，好评率99%" → [产品介绍, 信任背书]
#
# 实现：
# - 将分类头改为sigmoid（每标签独立二分类）
# - 每个标签的阈值独立设置
# - 归因时按标签权重分配GMV
#
# 挑战：
# - 标签间相关性需要处理（价格福利和逼单催促高度相关）
# - 归因逻辑更复杂
# - 商家可能更难理解"一句话属于两个标签"
#
