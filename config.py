# ==================== DID归因配置 ====================
# 解决的问题：哪句话真正带来了订单，怎么排除自然流量干扰

# 时间窗口定义：7个窗口看用户下单行为
# 0-1分钟：冲动消费，主要是逼单话术的效果
# 1-5分钟：短期决策，价格福利的效果
# 5-15分钟：考虑后下单，产品介绍的效果
# 15-30分钟：深度种草，痛点共鸣的效果
# 30分钟-1小时：犹豫后下单，综合效果
# 1-3小时：延迟决策，可能是看了回放
